const storage = {
  get(store, key) { try { return window[store].getItem(key); } catch { return null; } },
  set(store, key, value) { try { window[store].setItem(key, value); } catch { /* private mode: fine */ } },
};

const state = { lang: 'pt-BR', os: null, release: null /* {status: 'ok'|'none'|'unknown', tag, date, sizes} */ };
const PT = { text: new Map(), attr: new Map() };

function capturePortuguese() {
  document.querySelectorAll('[data-i18n]').forEach((el) => PT.text.set(el, el.textContent));
  document.querySelectorAll('[data-i18n-html]').forEach((el) => PT.text.set(el, el.innerHTML));
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    PT.attr.set(el, Object.fromEntries(attrPairs(el).map(([attr]) => [attr, el.getAttribute(attr)])));
  });
}

function attrPairs(el) {
  return el.dataset.i18nAttr.split(';').map((pair) => pair.split(':').map((s) => s.trim())).filter((p) => p.length === 2);
}

function applyLanguage(lang) {
  state.lang = lang;
  const en = lang === 'en';
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    el.textContent = en && EN[key] ? EN[key] : PT.text.get(el);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.dataset.i18nHtml;
    el.innerHTML = en && EN[key] ? EN[key] : PT.text.get(el); // trusted, static strings from this file or the page
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const original = PT.attr.get(el);
    for (const [attr, key] of attrPairs(el)) el.setAttribute(attr, en && EN[key] ? EN[key] : original[attr]);
  });
  const t = DYN[lang];
  document.title = t.title;
  const toggle = document.getElementById('lang-toggle');
  toggle.textContent = t.toggleShort;
  toggle.setAttribute('aria-label', t.toggle);
  toggle.setAttribute('lang', t.toggleLang);
  renderHero();
  renderRelease();
  renderVideoToggle();
}

// ---------- Operating system ----------
function detectOS() {
  const uaPlatform = navigator.userAgentData && navigator.userAgentData.platform;
  const ua = `${uaPlatform || ''} ${navigator.platform || ''} ${navigator.userAgent || ''}`.toLowerCase();
  if (/android|iphone|ipad|ipod|mobile/.test(ua)) return 'mobile';
  if (/windows|win32|win64|wow64/.test(ua)) return 'windows';
  if (/mac|darwin/.test(ua)) return 'macos';
  if (/linux|x11|cros|ubuntu|fedora/.test(ua)) return 'linux';
  return null;
}

function renderHero() {
  const t = DYN[state.lang];
  const link = document.getElementById('hero-download');
  const label = document.getElementById('hero-download-label');
  const file = document.getElementById('hero-download-file');
  const info = OS_INFO[state.os];
  if (!info) {
    // Unknown or a phone: the button goes to the download list.
    link.href = '#download';
    label.textContent = state.lang === 'en' ? EN['hero.download'] : PT.text.get(label);
    file.textContent = state.os === 'mobile' ? t.mobile : 'Windows · macOS · Linux';
    return;
  }
  const soon = state.release && state.release.status === 'none';
  link.href = soon ? RELEASES_URL : downloadUrl(info.file);
  label.textContent = soon ? `${t.soonBtn} · ${info.name}` : t.downloadFor(info.name);
  const size = state.release && state.release.sizes && state.release.sizes[info.file];
  file.textContent = [info.file, size && formatSize(size)].filter(Boolean).join(' · ');
}

function markYourCard() {
  const info = OS_INFO[state.os];
  document.querySelectorAll('.dl-card').forEach((card) => card.classList.toggle('is-yours', !!info && card.dataset.os === info.card));
  if (!info) return;
  // The visitor's card goes first in the list.
  const card = document.querySelector(`.dl-card[data-os="${info.card}"]`);
  if (card && card.parentElement.firstElementChild !== card) card.parentElement.prepend(card);
}

const downloadUrl = (file) => `https://github.com/${REPO}/releases/latest/download/${file}`;

// ---------- Latest release ----------
function formatSize(bytes) {
  const mb = bytes / (1024 * 1024);
  const n = new Intl.NumberFormat(state.lang, { maximumFractionDigits: mb < 10 ? 1 : 0 }).format(mb);
  return `${n} MB`;
}

function formatDate(iso) {
  if (!iso) return '';
  try {
    return new Intl.DateTimeFormat(state.lang, { day: 'numeric', month: 'long', year: 'numeric' }).format(new Date(iso));
  } catch { return ''; }
}

async function loadRelease() {
  const cached = storage.get('sessionStorage', CACHE_KEY);
  if (cached) {
    try {
      const data = JSON.parse(cached);
      if (Date.now() - data.at < CACHE_MS) return data.release;
    } catch { /* ignore a broken cache */ }
  }
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 6000);
  let release;
  try {
    const res = await fetch(API_LATEST, { headers: { Accept: 'application/vnd.github+json' }, signal: controller.signal, credentials: 'omit' });
    if (res.status === 404) {
      release = { status: 'none' }; // no published release yet (a draft does not count)
    } else if (res.ok) {
      const json = await res.json();
      const sizes = {};
      for (const asset of json.assets || []) sizes[asset.name] = asset.size;
      release = { status: 'ok', tag: String(json.tag_name || ''), date: json.published_at || '', url: json.html_url || RELEASES_URL, sizes };
    } else {
      release = { status: 'unknown' }; // rate limit or an outage: the stable links still work
    }
  } catch {
    release = { status: 'unknown' };
  } finally {
    clearTimeout(timer);
  }
  if (release.status !== 'unknown') storage.set('sessionStorage', CACHE_KEY, JSON.stringify({ at: Date.now(), release }));
  return release;
}

function releasesLink(text, href = RELEASES_URL) {
  const a = document.createElement('a');
  a.className = 'link';
  a.href = href;
  a.rel = 'noopener';
  a.textContent = text;
  return a;
}

function renderRelease() {
  const t = DYN[state.lang];
  const status = document.getElementById('release-status');
  const release = state.release;
  status.replaceChildren();
  document.querySelectorAll('.dl-card').forEach((card) => {
    const link = card.querySelector('.dl-link');
    const size = card.querySelector('.dl-size');
    const file = card.dataset.file;
    const soon = release && release.status === 'none';
    link.href = soon ? RELEASES_URL : downloadUrl(file);
    const bytes = release && release.sizes && release.sizes[file];
    size.textContent = bytes ? `· ${formatSize(bytes)}` : '';
  });
  if (!release) return;
  if (release.status === 'ok') {
    const pill = document.createElement('span');
    pill.className = 'pill';
    pill.textContent = t.latest;
    status.append(pill, `${t.version(release.tag, formatDate(release.date))} · `, releasesLink(t.releases, release.url));
  } else if (release.status === 'none') {
    const pill = document.createElement('span');
    pill.className = 'pill pill-soon';
    pill.textContent = t.soonPill;
    status.append(pill, t.soon, releasesLink(t.releases), '.');
  } else {
    status.append(t.unknown, releasesLink(t.releases), '.');
  }
}

// ---------- Example clip ----------
const motion = window.matchMedia('(prefers-reduced-motion: reduce)');
let userPaused = false;
let inView = true;

function renderVideoToggle() {
  const video = document.getElementById('story-loop');
  const toggle = document.getElementById('video-toggle');
  if (!video || !toggle) return;
  const paused = video.paused;
  const t = DYN[state.lang];
  toggle.setAttribute('aria-pressed', String(paused));
  document.getElementById('video-toggle-label').textContent = paused ? t.play : t.pause;
}

function syncVideo() {
  const video = document.getElementById('story-loop');
  if (!video) return;
  const shouldPlay = !motion.matches && !userPaused && inView && !document.hidden;
  if (shouldPlay && video.paused) {
    const p = video.play();
    if (p && p.catch) p.catch(() => renderVideoToggle());
  } else if (!shouldPlay && !video.paused) {
    video.pause();
  }
}

function setupVideo() {
  const video = document.getElementById('story-loop');
  const toggle = document.getElementById('video-toggle');
  if (!video || !toggle) return;
  toggle.hidden = false;
  video.addEventListener('play', renderVideoToggle);
  video.addEventListener('pause', renderVideoToggle);
  toggle.addEventListener('click', () => {
    if (video.paused) {
      userPaused = false;
      const p = video.play();
      if (p && p.catch) p.catch(() => {});
    } else {
      userPaused = true;
      video.pause();
    }
  });
  if (motion.addEventListener) motion.addEventListener('change', syncVideo);
  document.addEventListener('visibilitychange', syncVideo);
  if ('IntersectionObserver' in window) {
    new IntersectionObserver((entries) => {
      inView = entries.some((e) => e.isIntersecting);
      syncVideo();
    }, { threshold: 0.15 }).observe(video);
  }
  syncVideo();
  renderVideoToggle();
}

// ---------- Start ----------
function initialLanguage() {
  const param = new URLSearchParams(location.search).get('lang');
  if (param === 'en' || param === 'pt-BR' || param === 'pt') return param === 'en' ? 'en' : 'pt-BR';
  const saved = storage.get('localStorage', LANG_KEY);
  return saved === 'en' ? 'en' : 'pt-BR';
}

function start() {
  document.documentElement.classList.replace('no-js', 'js');
  capturePortuguese();
  state.os = detectOS();
  markYourCard();
  setupVideo();
  applyLanguage(initialLanguage());
  document.getElementById('lang-toggle').addEventListener('click', () => {
    const next = state.lang === 'en' ? 'pt-BR' : 'en';
    storage.set('localStorage', LANG_KEY, next);
    const url = new URL(location.href);
    url.searchParams.delete('lang');
    history.replaceState(null, '', url);
    applyLanguage(next);
  });
  loadRelease().then((release) => {
    state.release = release;
    renderHero();
    renderRelease();
  });
}

start();
